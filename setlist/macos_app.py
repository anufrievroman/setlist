"""Create a macOS .app bundle that launches Setlist with the current Python."""

import os
import plistlib
import shutil
import stat
import subprocess
import sys
import sysconfig
from pathlib import Path

from . import __version__

APP_NAME = "Setlist"
BUNDLE_ID = "com.setlist.Setlist"
RESOURCES = Path(__file__).parent / "resources"

# A framework Python's `bin/python3` is a stub that relaunches the interpreter from
# inside Python.app, so macOS would show the app as "Python". Instead, keep a copy of
# the real interpreter inside our bundle (refreshed on each launch, so Python upgrades
# don't break it) and point it at the right environment via __PYVENV_LAUNCHER__.
LAUNCHER = """#!/bin/sh
# Generated by `setlist --install-app`. Re-run that command if Python moves.
PYTHON="{python}"
REAL="{real}"
BIN="$(cd "$(dirname "$0")" && pwd)/{name}"
if [ -n "$REAL" ] && [ -x "$REAL" ]; then
    cmp -s "$REAL" "$BIN" || cp -f "$REAL" "$BIN"
    export __PYVENV_LAUNCHER__="$PYTHON"
    exec "$BIN" -m setlist "$@"
fi
exec "$PYTHON" -m setlist "$@"
"""


def framework_interpreter():
    """Path of the real interpreter inside Python.app for framework builds, else ''."""
    if not sysconfig.get_config_var("PYTHONFRAMEWORK"):
        return ""
    real = Path(sys.base_prefix) / "Resources" / "Python.app" / "Contents" / "MacOS" / "Python"
    return str(real) if real.exists() else ""


def install_app(destination=None):
    """Build Setlist.app in ~/Applications (or `destination`) and return its path."""
    if sys.platform != "darwin":
        raise SystemExit("--install-app is only supported on macOS.")

    target_dir = Path(destination).expanduser() if destination else Path.home() / "Applications"
    target_dir.mkdir(parents=True, exist_ok=True)
    app = target_dir / f"{APP_NAME}.app"
    if app.exists():
        shutil.rmtree(app)

    contents = app / "Contents"
    (contents / "MacOS").mkdir(parents=True)
    (contents / "Resources").mkdir()

    with open(contents / "Info.plist", "wb") as f:
        plistlib.dump(
            {
                "CFBundleName": APP_NAME,
                "CFBundleDisplayName": APP_NAME,
                "CFBundleIdentifier": BUNDLE_ID,
                "CFBundleVersion": __version__,
                "CFBundleShortVersionString": __version__,
                "CFBundlePackageType": "APPL",
                "CFBundleExecutable": "launcher",
                "CFBundleIconFile": "Setlist.icns",
                "LSMinimumSystemVersion": "11.0",
                "NSHighResolutionCapable": True,
            },
            f,
        )

    launcher = contents / "MacOS" / "launcher"
    launcher.write_text(LAUNCHER.format(python=sys.executable, real=framework_interpreter(), name=APP_NAME))
    launcher.chmod(launcher.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    shutil.copy(RESOURCES / "icon.icns", contents / "Resources" / "Setlist.icns")

    # Ask Launch Services to pick up the new bundle (and its icon) right away.
    lsregister = (
        "/System/Library/Frameworks/CoreServices.framework/Frameworks/"
        "LaunchServices.framework/Support/lsregister"
    )
    if os.path.exists(lsregister):
        subprocess.run([lsregister, "-f", str(app)], check=False)
    return app
